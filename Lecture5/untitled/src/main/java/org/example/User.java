package org.example;

import org.springframework.stereotype.Component;

public class User {

    public String name;
    public int age;

    // which Name and which age is required
    public User(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
